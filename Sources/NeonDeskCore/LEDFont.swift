    public static func textWidth(_ text: String, pitch: CGFloat, gap: CGFloat) -> CGFloat {
        let count = CGFloat(text.count)
        guard count > 0 else { return 0 }
        return count * 5 * pitch + max(0, count - 1) * gap
    }

    public static func textHeight(pitch: CGFloat) -> CGFloat {
        7 * pitch
    }

    public static func drawText(
        _ ctx: CGContext,
        text: String,
        origin: CGPoint,
        pitch: CGFloat,
        gap: CGFloat,
        radius: CGFloat,
        color: RGB,
        intensity: CGFloat,
        scanX: CGFloat? = nil,
        scanWidth: CGFloat = 140,
        bleach: CGFloat = 0.35,
        coreWhite: CGFloat = 0.12,
        drawOffDots: Bool = true
    ) {
        let upper = text.uppercased()
        for (index, char) in upper.enumerated() {
            let glyph = glyphs[char] ?? glyphs[" "]!
            let left = origin.x + CGFloat(index) * (5 * pitch + gap)
            for (row, bits) in glyph.enumerated() {
                for (col, bit) in bits.enumerated() {
                    let cx = left + CGFloat(col) * pitch + pitch / 2
                    let cy = origin.y + CGFloat(row) * pitch + pitch / 2
                    var local = intensity
                    if let scanX {
                        let dist = abs(cx - scanX)
                        if dist < scanWidth {
                            local = min(1, intensity + (1 - dist / scanWidth) * 0.55)
                        }
                    }
                    if bit == "1" {
                        let halo = Palette.bg.mix(color, 0.45 * local)
                        let core = color.mix(Palette.white, coreWhite * local)
                        let r = max(1, radius + local * 0.8)
                        fillCircle(ctx, cx: cx, cy: cy, r: r + 3, color: halo)
                        fillCircle(ctx, cx: cx, cy: cy, r: r, color: core)
                        let highlight = max(1, r / 3)
                        fillCircle(
                            ctx,
                            cx: cx - 0.4,
                            cy: cy - 1,
                            r: highlight,
                            color: core.mix(Palette.white, bleach)
                        )
                    } else if drawOffDots {
                        let dimR = max(1, radius - 2)
                        fillCircle(ctx, cx: cx, cy: cy, r: dimR, color: Palette.dim)
                    }
                }
            }
        }
    }
}

public func fillCircle(_ ctx: CGContext, cx: CGFloat, cy: CGFloat, r: CGFloat, color: RGB) {
    ctx.setFillColor(color.cgColor)
    ctx.fillEllipse(in: CGRect(x: cx - r, y: cy - r, width: r * 2, height: r * 2))
}
